#!/usr/bin/env python3
"""Rebuild eabu-dish/python/my_utils/search_real_words.txt (run after changing search.TERMS).

Search corrects misspellings to the nearest vocabulary word ("chienese" -> "chinese"), but must never
"correct" a real word ("chair" is not "hair", "train" is not "drain"). This lists every English word
(macOS /usr/share/dict/words, plus its -s/-es/-ed/-ing forms) that fix_word would otherwise change;
search.fix_word leaves those alone. Only words near the vocabulary are kept, so the file stays small.

    python3 scripts/build_search_words.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eabu-dish", "python"))

from my_utils import search  # noqa: E402

OUT = os.path.join(ROOT, "eabu-dish", "python", "my_utils", "search_real_words.txt")
DICT = "/usr/share/dict/words"


def main():
    search.REAL_WORDS = frozenset()  # judge every word afresh
    base = {w.strip() for w in open(DICT, encoding="utf-8")}
    base = {w for w in base if w.isalpha() and w.islower() and 4 <= len(w) <= 14}
    forms = set()
    for w in base:
        forms |= {w, w + "s", w + "es", w + "ed", w + "ing"}
        if w.endswith("e"):
            forms |= {w[:-1] + "ing", w + "d"}
    keep = sorted(w for w in forms if search.fix_word(w))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# Real words search must not correct. Generated by scripts/build_search_words.py.\n")
        f.write("\n".join(keep) + "\n")
    print(f"{len(keep)} words -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
